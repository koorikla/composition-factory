func TestRoundTripGoldenCompositions(t *testing.T) {
	paths := []string{
		"../emit/testdata/native-composition.golden.yaml",
		"../emit/testdata/pipeline_composition.golden.yaml",
		"../../testdata/xqueue-pipeline.composition.golden.yaml",
	}

	for _, relPath := range paths {
		t.Run(filepath.Base(relPath), func(t *testing.T) {
			raw, err := os.ReadFile(relPath)
			if err != nil {
				t.Fatalf("failed to read test fixture: %v", err)
			}

			m, err := ParseComposition(raw)
			if err != nil {
				t.Fatalf("ParseComposition failed: %v", err)
			}

			// Apply with zero edits must be 100% byte-identical
			patched, err := Apply(m)
			if err != nil {
				t.Fatalf("Apply failed: %v", err)
			}

			if !bytes.Equal(patched, raw) {
				t.Fatalf("Round-trip identity failure: output differs from input\nGot:\n%s\nWant:\n%s", string(patched), string(raw))
			}
		})
	}
}

func TestSingleFieldLiteralSplice(t *testing.T) {
	raw, err := os.ReadFile("../emit/testdata/native-composition.golden.yaml")
	if err != nil {
		t.Fatalf("failed to read fixture: %v", err)
	}

	m, err := ParseComposition(raw)
	if err != nil {
		t.Fatalf("ParseComposition failed: %v", err)
	}

	if len(m.Resources) == 0 {
		t.Fatalf("expected parsed resources, got 0")
	}

	queueRes := m.Resources[0]
	if queueRes.Name != "main-queue" {
		t.Fatalf("expected resource main-queue, got %s", queueRes.Name)
	}

	edit, err := SetFieldLiteral(queueRes, "region", "us-east-1")
	if err != nil {
		t.Fatalf("SetFieldLiteral failed: %v", err)
	}

	patched, err := Apply(m, edit)
	if err != nil {
		t.Fatalf("Apply edit failed: %v", err)
	}

	if !strings.Contains(string(patched), "region: 'us-east-1'") {
		t.Errorf("expected patched output to contain region: 'us-east-1'\nGot:\n%s", string(patched))
	}
	if strings.Contains(string(patched), "region: 'eu-north-1'") {
		t.Errorf("expected old region to be replaced")
	}

	// Verify that header comments were preserved
	if !strings.Contains(string(patched), "# Generated by compositionfactory. Do not edit.") {
		t.Errorf("header comments were destroyed")
	}
}

